"""Generate the protocol package and docs from schema/ops.v1.json (A1.02, ADR-0003).

    uv run tools/gen_protocol.py           # write
    uv run tools/gen_protocol.py --check   # exit 1 if anything is stale (CI)

Outputs (never edit them by hand):
    packages/mphone-protocol/src/mphone_protocol/_generated/{schema,models,ops,errors}.py
    docs/protocol.md

The schema uses a small JSON Schema subset on purpose: object, array, string, integer, number,
boolean, null, enum, const, $ref, anyOf-with-null and type lists. Anything else is rejected here
so the generated Python never silently loses a constraint.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_PATH = ROOT / "packages/mphone-protocol/schema/ops.v1.json"
OUT_DIR = ROOT / "packages/mphone-protocol/src/mphone_protocol/_generated"
DOC_PATH = ROOT / "docs/protocol.md"

HEADER = (
    "# GENERATED by tools/gen_protocol.py from packages/mphone-protocol/schema/ops.v1.json.\n"
    "# Do not edit by hand: change the schema and regenerate (CLAUDE.md §5).\n"
)
SIMPLE = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}
FORBID_EXTRA = {"OpRequest", "Selector"}
KEYWORDS = {"class", "from", "in", "is", "not", "and", "or", "def", "global", "pass", "import"}
CONSTRAINTS = {
    "minimum": "ge",
    "maximum": "le",
    "exclusiveMinimum": "gt",
    "exclusiveMaximum": "lt",
    "minLength": "min_length",
    "maxLength": "max_length",
}
ALLOWED_KEYS = {
    "type",
    "enum",
    "const",
    "$ref",
    "anyOf",
    "items",
    "properties",
    "required",
    "default",
    "description",
    "additionalProperties",
    *CONSTRAINTS,
}


class SchemaError(Exception):
    pass


def ref_name(ref: str) -> str:
    prefix = "#/$defs/"
    if not ref.startswith(prefix):
        raise SchemaError(f"only local $defs refs are supported, got {ref!r}")
    return ref[len(prefix) :]


def literal(values: list[Any]) -> str:
    return "Literal[" + ", ".join(json.dumps(v) for v in values) + "]"


def py_type(s: dict[str, Any], where: str) -> str:
    unknown = set(s) - ALLOWED_KEYS - {k for k in s if k.startswith("x-")}
    if unknown:
        raise SchemaError(f"{where}: unsupported keywords {sorted(unknown)}")
    if not s or set(s) <= {"description", "default"}:
        return "Any"
    if "$ref" in s:
        return ref_name(s["$ref"])
    if "const" in s:
        return literal([s["const"]])
    if "anyOf" in s:
        parts = [py_type(x, where) for x in s["anyOf"]]
        return " | ".join(parts)
    if "enum" in s:
        return literal(s["enum"])
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(py_type({**s, "type": one}, where) for one in t)
    if t in SIMPLE:
        return SIMPLE[t]
    if t == "array":
        return f"list[{py_type(s.get('items', {}), where + '[]')}]"
    if t == "object":
        if s.get("properties"):
            raise SchemaError(f"{where}: inline object with properties; move it to $defs")
        return "dict[str, Any]"
    raise SchemaError(f"{where}: cannot map {s!r}")


def field(name: str, s: dict[str, Any], required: bool, where: str) -> str:
    annotation = py_type(s, where)
    args: list[str] = []
    if not required:
        default = s.get("default")
        if isinstance(default, list | dict) and default:
            args.append(f"default_factory=lambda: {default!r}")
        elif isinstance(default, list):
            args.append(f"default_factory=list[{annotation.removeprefix('list[')}")
        elif isinstance(default, dict):
            args.append("default_factory=dict[str, Any]")
        else:
            args.append(f"default={default!r}")
            if default is None and "None" not in annotation and annotation != "Any":
                annotation += " | None"
    for key, kw in CONSTRAINTS.items():
        if key in s:
            args.append(f"{kw}={s[key]!r}")
    attr = name
    if name in KEYWORDS:
        attr = name + "_"
        args.append(f"alias={name!r}")
    if not args:
        return f"    {attr}: {annotation}"
    return f"    {attr}: {annotation} = Field({', '.join(args)})"


def model(name: str, props: dict[str, Any], required: list[str], forbid: bool, doc: str | None) -> str:
    extra = "forbid" if forbid else "ignore"
    lines = [f"class {name}(BaseModel):"]
    if doc:
        lines.append(f"    {json.dumps(doc, ensure_ascii=False)}")
        lines.append("")
    lines.append(
        f'    model_config = ConfigDict(extra="{extra}", populate_by_name=True, serialize_by_alias=True)'
    )
    lines.append("")
    if not props:
        lines.append("    pass")
    for prop, s in props.items():
        lines.append(field(prop, s, prop in required, f"{name}.{prop}"))
    return "\n".join(lines)


def class_name(op: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[._]", op)) + "Args"


def error_class(code: str) -> str:
    if code == "INTERNAL":
        return "InternalError"
    return "".join(part.capitalize() for part in code.split("_"))


def gen_models(schema: dict[str, Any]) -> str:
    defs: dict[str, Any] = schema["$defs"]
    out = [
        HEADER,
        "from __future__ import annotations\n",
        "from typing import Any, Literal\n",
        "from pydantic import BaseModel, ConfigDict, Field\n",
    ]
    aliases: list[str] = []
    classes: list[str] = []
    for name, s in defs.items():
        if s.get("type") == "object":
            classes.append(
                model(
                    name,
                    s.get("properties", {}),
                    s.get("required", []),
                    name in FORBID_EXTRA,
                    s.get("description"),
                )
            )
        else:
            aliases.append(f"{name} = {py_type(s, name)}")
    out.append("\n".join(aliases) + "\n")
    out.extend(c + "\n" for c in classes)
    out.append("# --- op arguments " + "-" * 60 + "\n")
    for op, spec in schema["x-ops"].items():
        doc = f"Arguments of {op}: {spec['description_en']}"
        out.append(model(class_name(op), spec["args"], spec.get("required", []), True, doc) + "\n")
    names = [n for n, s in defs.items() if s.get("type") == "object"]
    names += [class_name(op) for op in schema["x-ops"]]
    out.append("\n".join(f"{n}.model_rebuild()" for n in names) + "\n")
    return "\n\n".join(out)


def gen_ops(schema: dict[str, Any]) -> str:
    ops: dict[str, Any] = schema["x-ops"]
    lines = [
        HEADER,
        "from __future__ import annotations\n",
        "from dataclasses import dataclass",
        "from typing import Any, Literal\n",
        "from pydantic import BaseModel\n",
        "from . import models\n",
        f"PROTOCOL_VERSION = {schema['x-protocol-version']!r}\n",
        'SideEffect = Literal["none", "input", "nav", "apps", "device"]\n',
        "",
        "@dataclass(frozen=True)",
        "class OpSpec:",
        "    name: str",
        "    args_model: type[BaseModel]",
        "    result_schema: dict[str, Any]",
        "    timeout_ms: int",
        "    side_effect: SideEffect",
        "    sensitive_args: tuple[str, ...]",
        "    description_tr: str",
        "    description_en: str",
        "",
        "",
        "OP_SPECS: dict[str, OpSpec] = {",
    ]
    for op, spec in ops.items():
        sensitive = tuple(spec.get("x-sensitive-args", []))
        lines.append(
            f"    {op!r}: OpSpec({op!r}, models.{class_name(op)}, {spec['result']!r}, {spec['timeout_ms']}, "
            f"{spec['side_effect']!r}, {sensitive!r}, "
            f"{spec['description_tr']!r}, {spec['description_en']!r}),"
        )
    lines.append("}\n")
    lines.append("OP_NAMES: tuple[str, ...] = tuple(OP_SPECS)\n")
    return "\n".join(lines)


def gen_errors(schema: dict[str, Any]) -> str:
    code_def = schema["$defs"]["ErrorCode"]
    retryable = set(code_def["x-retryable"])
    tr = code_def["x-description-tr"]
    lines = [
        HEADER,
        "from __future__ import annotations\n",
        "from typing import Any, ClassVar\n",
        "from .models import ErrorCode, ErrorInfo\n",
        "",
        "class MphoneError(RuntimeError):",
        '    """Base of every protocol error. `user_action` is the one thing a human must do, if any."""',
        "",
        '    code: ClassVar[ErrorCode] = "INTERNAL"',
        "    retryable_default: ClassVar[bool] = False",
        "",
        "    def __init__(",
        "        self,",
        "        message: str,",
        "        *,",
        "        user_action: str | None = None,",
        "        details: dict[str, Any] | None = None,",
        "        retryable: bool | None = None,",
        "    ) -> None:",
        "        super().__init__(message)",
        "        self.message = message",
        "        self.user_action = user_action",
        "        self.details: dict[str, Any] = details or {}",
        "        self.retryable = self.retryable_default if retryable is None else retryable",
        "",
        "    def __str__(self) -> str:",
        "        if self.user_action:",
        '            return f"{self.message} — {self.user_action}"',
        "        return self.message",
        "",
        "    def to_info(self) -> ErrorInfo:",
        "        return ErrorInfo(",
        "            code=self.code, message=self.message, retryable=self.retryable,",
        "            user_action=self.user_action, details=self.details,",
        "        )",
        "",
        "    @staticmethod",
        "    def from_info(info: ErrorInfo) -> MphoneError:",
        "        cls = ERROR_CLASSES.get(info.code, InternalError)",
        "        return cls(info.message, user_action=info.user_action, details=info.details,",
        "                   retryable=info.retryable)",
        "",
    ]
    for code in code_def["enum"]:
        name = error_class(code)
        lines += [
            "",
            f"class {name}(MphoneError):",
            f"    {json.dumps(tr[code], ensure_ascii=False)}",
            "",
            f"    code = {code!r}",
            f"    retryable_default = {code in retryable}",
            "",
        ]
    lines.append("\nERROR_CLASSES: dict[str, type[MphoneError]] = {")
    lines += [f"    {code!r}: {error_class(code)}," for code in code_def["enum"]]
    lines.append("}")
    lines.append(f"\nERROR_DESCRIPTIONS_TR: dict[str, str] = {tr!r}\n")
    return "\n".join(lines)


def gen_schema_module(schema: dict[str, Any]) -> str:
    text = json.dumps(schema, ensure_ascii=False, indent=1, sort_keys=False)
    return (
        HEADER
        + "\nimport json\nfrom typing import Any\n\n"
        + f"SCHEMA: dict[str, Any] = json.loads(r'''{text}''')\n"
    )


def gen_doc(schema: dict[str, Any]) -> str:
    ops: dict[str, Any] = schema["x-ops"]
    code_def = schema["$defs"]["ErrorCode"]
    out = [
        "# Protokol v1 — Op Referansı",
        "",
        "> **Üretilmiş dosya** (`tools/gen_protocol.py`). Elle düzenleme; "
        "`packages/mphone-protocol/schema/ops.v1.json`'ı değiştirip yeniden üret.",
        f"> Protokol sürümü: `{schema['x-protocol-version']}` · Op sayısı: {len(ops)} · Tasarım: Plan.md §7.",
        "",
        "## Op'lar",
        "",
        "| Op | Argümanlar (varsayılan) | Sonuç | Yan etki | Zaman aşımı | Açıklama |",
        "|---|---|---|---|---|---|",
    ]
    for op, spec in ops.items():
        req = set(spec.get("required", []))
        args = []
        for name, s in spec["args"].items():
            label = (
                f"`{name}`" if name in req else f"`{name}={json.dumps(s.get('default'), ensure_ascii=False)}`"
            )
            args.append(label)
        result = py_type(spec["result"], op) if spec["result"] else "Any"
        out.append(
            f"| `{op}` | {', '.join(args) or '—'} | `{result}` | {spec['side_effect']} | "
            f"{spec['timeout_ms'] // 1000} sn | {spec['description_tr']} |"
        )
    out += ["", "## Hata kodları", "", "| Kod | Tekrar denenebilir | Anlam |", "|---|---|---|"]
    retryable = set(code_def["x-retryable"])
    for code in code_def["enum"]:
        out.append(
            f"| `{code}` | {'evet' if code in retryable else 'hayır'} | "
            f"{code_def['x-description-tr'][code]} |"
        )
    out += ["", "## Tipler", ""]
    for name, s in schema["$defs"].items():
        if s.get("type") != "object":
            continue
        out.append(f"### {name}")
        if s.get("description"):
            out += ["", s["description"]]
        out += ["", "| Alan | Tip | Zorunlu |", "|---|---|---|"]
        req = set(s.get("required", []))
        for prop, ps in s.get("properties", {}).items():
            out.append(f"| `{prop}` | `{py_type(ps, name)}` | {'✓' if prop in req else ''} |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def outputs(schema: dict[str, Any]) -> dict[Path, str]:
    return {
        OUT_DIR / "__init__.py": HEADER,
        OUT_DIR / "schema.py": gen_schema_module(schema),
        OUT_DIR / "models.py": gen_models(schema),
        OUT_DIR / "ops.py": gen_ops(schema),
        OUT_DIR / "errors.py": gen_errors(schema),
        DOC_PATH: gen_doc(schema),
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    try:
        files = outputs(schema)
    except SchemaError as e:
        print(f"schema error: {e}", file=sys.stderr)
        return 2
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        if stale:
            print("run: uv run tools/gen_protocol.py", file=sys.stderr)
        return 1 if stale else 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for p in stale:
        p.write_text(files[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
